    private Franchise(int id, string name) 
        : base(id, name) { }

    public static Franchise Find(int id)
        => All.SingleOrDefault(franchise => franchise.Id == id);

    public static Franchise Find(string name)
        => All.SingleOrDefault(franchise => franchise.Name == name);

    public static Franchise[] GetAll(SportLeagueLevel sport)
    {
        if (sport == SportLeagueLevel.MajorLeagueBaseball)
            return Baseball;

        if (sport == SportLeagueLevel.NationalBasketballAssociation)
            return Basketball;

        if (sport == SportLeagueLevel.NationalFootballLeague)
            return Football;

        if (sport == SportLeagueLevel.NationalHockeyLeague)
            return Hockey;

        return All;
    }

    public static Franchise[] GetAll(params Sport[] sports)
    {
        if (sports.IsNullOrEmpty())
            return All;

        var franchises = new List<Franchise>();

        if (sports.Any(sport => sport == Sport.Baseball))
            franchises.AddRange(Baseball);

        if (sports.Any(sport => sport == Sport.Basketball))
            franchises.AddRange(Basketball);

        if (sports.Any(sport => sport == Sport.Football))
            franchises.AddRange(Football);

        if (sports.Any(sport => sport == Sport.Hockey))
            franchises.AddRange(Hockey);

        return franchises.OrderBy(franchise => franchise.Name).ToArray();
    }

    public static Sport GetSport(int id)
    {
        var franchise = Find(id);

        if (Baseball.Contains(franchise))
            return Sport.Baseball;

        if (Basketball.Contains(franchise))
            return Sport.Basketball;

        if (Football.Contains(franchise))
            return Sport.Football;

        if (Hockey.Contains(franchise))
            return Sport.Hockey;

        return null;
    }
